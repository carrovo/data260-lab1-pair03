#!/bin/sh
# Creates .env.compose from .env.compose.example with fresh random secrets.
# Never overwrites an existing file. The file is git-ignored; never commit it.
#   sh scripts/make_env.sh        (or: make env)
set -e
if [ -f .env.compose ]; then
  echo ".env.compose already exists, left unchanged."
  exit 0
fi
rand() { openssl rand -hex 24; }
{
  echo "# Generated by scripts/make_env.sh. Git-ignored: do not commit."
  echo "MYSQL_ROOT_PASSWORD=$(rand)"
  echo "MYSQL_PASSWORD=$(rand)"
  echo "JWT_SECRET_KEY=$(rand)"
} > .env.compose
chmod 600 .env.compose
echo "Created .env.compose with random secrets (never printed here)."
